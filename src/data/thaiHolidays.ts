/**
 * ดึงรายการวันหยุดราชการประจำเดือน
 * @param yearCE ปี ค.ศ.
 * @param monthZeroIndexed เดือน (0 = ม.ค., 11 = ธ.ค.)
 */
export function getHolidaysForMonth(yearCE: number, monthZeroIndexed: number): Array<ThaiPublicHoliday & { day: number }> {
  const holidays = THAI_PUBLIC_HOLIDAYS[yearCE] || [];
  const monthStr = String(monthZeroIndexed + 1).padStart(2, '0');
  const prefix = `${yearCE}-${monthStr}-`;

  return holidays
    .filter(h => h.date.startsWith(prefix))
    .map(h => ({
      ...h,
      day: parseInt(h.date.slice(8))
    }))
    .sort((a, b) => a.day - b.day);
}

/**
 * ดึงรายการวันหยุดราชการประจำปี
 * @param yearCE ปี ค.ศ.
 */
export function getHolidaysForYear(yearCE: number): ThaiPublicHoliday[] {
  return THAI_PUBLIC_HOLIDAYS[yearCE] || [];
}
